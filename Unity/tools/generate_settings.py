"""Regenerate the shared native / Unity settings contract. Run from any directory."""
import json
from pathlib import Path
root = Path(__file__).resolve().parents[1]
settings = json.loads((root / "Settings/settings.json").read_text())
assert [s["id"] for s in settings] == list(range(len(settings)))
lines = ["// Generated by Unity/tools/generate_settings.py. Do not edit.",
         f"constexpr int FitdSettingCount={len(settings)};",
         "static float readSetting(int id) {", "    switch (id) {"]
for s in settings:
    i = s["id"]
    expr = "g_remasterConfig." + s["key"]
    if s["kind"] == "key": expr = f"getKeyBinding((KeyAction){i-53}).keyboard"
    if s["kind"] == "pad": expr = f"getKeyBinding((KeyAction){i-63}).gamepadButton"
    lines.append(f"    case {i}: return float({expr});")
lines += ["    }", "    return 0;", "}", "static void writeSetting(int id, float value) {", "    switch (id) {"]
for s in settings:
    i = s["id"]
    value = "value"
    if s["kind"] in ("toggle", "fullscreen"): value = "value > 0.5f"
    if s["kind"] in ("int", "key", "pad"): value = "int(std::round(value))"
    lines += [f'    case {i}:', f'        value = std::clamp(value, {s["min"]:.8f}f, {s["max"]:.8f}f);',
              f'        g_remasterConfig.{s["key"]} = {value};', '        break;']
lines += ["    }", "}", ""]
(root / "Native/generatedSettings.h").write_text("\n".join(lines))
for s in settings:
    if s["parent"] is None: s["parent"] = -1
(root / "Package/Runtime/Resources/FitdUI/SettingsSchema.json").write_text(json.dumps({"settings": settings}, indent=2) + "\n")
